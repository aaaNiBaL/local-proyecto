CREATE OR REPLACE FUNCTION public.audit_product_stock_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NEW.stock IS DISTINCT FROM OLD.stock THEN
    INSERT INTO public.inventory_stock_audit (
      product_id,
      product_name,
      previous_stock,
      new_stock,
      user_id,
      user_email,
      reason,
      transaction_id
    )
    VALUES (
      NEW.id,
      NEW.name,
      OLD.stock,
      NEW.stock,
      auth.uid(),
      auth.jwt() ->> 'email',
      'Movimiento de inventario',
      txid_current()
    );
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER products_stock_audit
  AFTER UPDATE OF stock ON public.products
  FOR EACH ROW
  EXECUTE FUNCTION public.audit_product_stock_change();

CREATE OR REPLACE FUNCTION public.link_stock_audit_movement()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NEW.product_id IS NOT NULL THEN
    UPDATE public.inventory_stock_audit
    SET movement_id = NEW.id,
        reason = COALESCE(NULLIF(btrim(NEW.note), ''), NEW.type::text)
    WHERE id = (
      SELECT id
      FROM public.inventory_stock_audit
      WHERE transaction_id = txid_current()
        AND product_id = NEW.product_id
        AND movement_id IS NULL
        AND adjustment_id IS NULL
      ORDER BY id DESC
      LIMIT 1
    );
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER movements_link_stock_audit
  AFTER INSERT ON public.movements
  FOR EACH ROW
  EXECUTE FUNCTION public.link_stock_audit_movement();

CREATE OR REPLACE FUNCTION public.link_stock_audit_adjustment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NEW.product_id IS NOT NULL THEN
    UPDATE public.inventory_stock_audit
    SET adjustment_id = NEW.id,
        reason = NEW.reason
    WHERE id = (
      SELECT id
      FROM public.inventory_stock_audit
      WHERE transaction_id = txid_current()
        AND product_id = NEW.product_id
        AND previous_stock = NEW.previous_stock
        AND new_stock = NEW.new_stock
        AND movement_id IS NULL
        AND adjustment_id IS NULL
      ORDER BY id DESC
      LIMIT 1
    );
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER inventory_adjustments_link_stock_audit
  AFTER INSERT ON public.inventory_adjustments
  FOR EACH ROW
  EXECUTE FUNCTION public.link_stock_audit_adjustment();

CREATE OR REPLACE FUNCTION public.register_entry(
  _product_id uuid,
  _qty numeric,
  _expires_at date DEFAULT NULL,
  _note text DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  product_row public.products%ROWTYPE;
  lot_id uuid;
BEGIN
  IF auth.uid() IS NULL OR NOT public.has_permission(auth.uid(), 'stock_manage') THEN
    RAISE EXCEPTION 'No tienes permiso para registrar entradas';
  END IF;
  IF _qty IS NULL OR _qty <= 0 OR _qty <> round(_qty, 3) THEN
    RAISE EXCEPTION 'Ingresa una cantidad válida de hasta tres decimales';
  END IF;
  IF _note IS NOT NULL AND length(btrim(_note)) > 500 THEN
    RAISE EXCEPTION 'El detalle no puede superar 500 caracteres';
  END IF;

  SELECT *
    INTO product_row
  FROM public.products
  WHERE id = _product_id
    AND active
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Producto no encontrado o inactivo';
  END IF;
  IF product_row.unit = 'unidad' AND _qty <> trunc(_qty) THEN
    RAISE EXCEPTION 'La cantidad de este producto debe ser un número entero';
  END IF;

  INSERT INTO public.lots (product_id, qty, qty_initial, expires_at, note)
  VALUES (_product_id, _qty, _qty, _expires_at, _note)
  RETURNING id INTO lot_id;

  UPDATE public.products
  SET stock = stock + _qty
  WHERE id = _product_id;

  INSERT INTO public.movements (
    type,
    product_id,
    product_name,
    unit,
    qty,
    amount,
    cost_amount,
    lot_id,
    user_id,
    note
  )
  VALUES (
    'in',
    product_row.id,
    product_row.name,
    product_row.unit,
    _qty,
    _qty * product_row.price,
    _qty * product_row.cost,
    lot_id,
    auth.uid(),
    _note
  );

  RETURN lot_id;
END
$$;

CREATE OR REPLACE FUNCTION public.enforce_movement_permission()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  allowed boolean;
BEGIN
  allowed := CASE NEW.type
    WHEN 'out' THEN public.has_permission(auth.uid(), 'sales')
    WHEN 'salida_manual' THEN public.has_permission(auth.uid(), 'stock_manage')
    WHEN 'in' THEN public.has_permission(auth.uid(), 'stock_manage')
    WHEN 'merma' THEN public.has_permission(auth.uid(), 'expiry_manage')
    WHEN 'devolucion' THEN public.has_permission(auth.uid(), 'sales')
    WHEN 'devolucion_proveedor' THEN public.has_permission(auth.uid(), 'stock_manage')
    ELSE false
  END;
  IF NOT allowed THEN
    RAISE EXCEPTION 'No tienes permiso para registrar este movimiento';
  END IF;
  RETURN NEW;
END
$$;

CREATE OR REPLACE FUNCTION public.register_manual_out(
  _product_id uuid,
  _qty numeric,
  _note text
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  product_row public.products%ROWTYPE;
  remaining numeric(12,3);
  quantity_to_remove numeric(12,3);
  lot_row record;
  movement_id uuid;
BEGIN
  IF auth.uid() IS NULL OR NOT public.has_permission(auth.uid(), 'stock_manage') THEN
    RAISE EXCEPTION 'No tienes permiso para registrar salidas manuales';
  END IF;
  IF _qty IS NULL OR _qty <= 0 THEN
    RAISE EXCEPTION 'Ingresa una cantidad válida';
  END IF;
  IF _note IS NULL OR length(btrim(_note)) = 0 OR length(btrim(_note)) > 500 THEN
    RAISE EXCEPTION 'El motivo es obligatorio y no puede superar 500 caracteres';
  END IF;

  SELECT *
    INTO product_row
  FROM public.products
  WHERE id = _product_id
    AND active
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Producto no encontrado o inactivo';
  END IF;
  IF product_row.unit = 'unidad' AND _qty <> trunc(_qty) THEN
    RAISE EXCEPTION 'La cantidad de este producto debe ser un número entero';
  END IF;
  IF _qty <> round(_qty, 3) THEN
    RAISE EXCEPTION 'La cantidad puede tener hasta tres decimales';
  END IF;
  IF product_row.stock < _qty THEN
    RAISE EXCEPTION 'Stock insuficiente (disponible: %)', product_row.stock;
  END IF;

  remaining := _qty;
  FOR lot_row IN
    SELECT id, qty
    FROM public.lots
    WHERE product_id = product_row.id
      AND qty > 0
    ORDER BY expires_at NULLS LAST, received_at
    FOR UPDATE
  LOOP
    EXIT WHEN remaining <= 0;
    quantity_to_remove := LEAST(lot_row.qty, remaining);
    UPDATE public.lots
    SET qty = qty - quantity_to_remove
    WHERE id = lot_row.id;
    remaining := remaining - quantity_to_remove;
  END LOOP;

  IF remaining > 0 THEN
    RAISE EXCEPTION 'El stock de los lotes no coincide con el inventario; no se registró la salida';
  END IF;

  UPDATE public.products
  SET stock = stock - _qty
  WHERE id = product_row.id;

  INSERT INTO public.movements (
    type,
    product_id,
    product_name,
    unit,
    qty,
    amount,
    cost_amount,
    user_id,
    note
  )
  VALUES (
    'salida_manual',
    product_row.id,
    product_row.name,
    product_row.unit,
    _qty,
    0,
    _qty * product_row.cost,
    auth.uid(),
    btrim(_note)
  )
  RETURNING id INTO movement_id;

  RETURN movement_id;
END
$$;

CREATE OR REPLACE FUNCTION public.adjust_inventory(
  _product_id uuid,
  _quantity_delta numeric,
  _reason text
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  product_row public.products%ROWTYPE;
  next_stock numeric(12,3);
  adjustment_id uuid;
  remaining numeric(12,3);
  lot_row record;
  quantity_to_remove numeric(12,3);
BEGIN
  IF auth.uid() IS NULL OR NOT public.has_role(auth.uid(), 'admin') THEN
    RAISE EXCEPTION 'Solo administradores pueden ajustar el inventario';
  END IF;
  IF _quantity_delta IS NULL OR _quantity_delta = 0 THEN
    RAISE EXCEPTION 'La cantidad del ajuste debe ser distinta de cero';
  END IF;
  IF _reason IS NULL OR length(btrim(_reason)) = 0 OR length(btrim(_reason)) > 500 THEN
    RAISE EXCEPTION 'El motivo es obligatorio y no puede superar 500 caracteres';
  END IF;

  SELECT *
    INTO product_row
  FROM public.products
  WHERE id = _product_id
    AND active
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Producto no encontrado o inactivo';
  END IF;
  IF product_row.unit = 'unidad' AND abs(_quantity_delta) <> trunc(abs(_quantity_delta)) THEN
    RAISE EXCEPTION 'La cantidad de este producto debe ser un número entero';
  END IF;
  IF abs(_quantity_delta) <> round(abs(_quantity_delta), 3) THEN
    RAISE EXCEPTION 'La cantidad puede tener hasta tres decimales';
  END IF;

  next_stock := product_row.stock + _quantity_delta;
  IF next_stock < 0 THEN
    RAISE EXCEPTION 'El ajuste no puede dejar el stock negativo (actual: %)', product_row.stock;
  END IF;

  IF _quantity_delta < 0 THEN
    remaining := abs(_quantity_delta);
    FOR lot_row IN
      SELECT id, qty
      FROM public.lots
      WHERE product_id = product_row.id
        AND qty > 0
      ORDER BY expires_at NULLS LAST, received_at
      FOR UPDATE
    LOOP
      EXIT WHEN remaining <= 0;
      quantity_to_remove := LEAST(lot_row.qty, remaining);
      UPDATE public.lots
      SET qty = qty - quantity_to_remove
      WHERE id = lot_row.id;
      remaining := remaining - quantity_to_remove;
    END LOOP;
    IF remaining > 0 THEN
      RAISE EXCEPTION 'El stock de los lotes no coincide con el inventario; no se registró el ajuste';
    END IF;
  ELSE
    INSERT INTO public.lots (product_id, qty, qty_initial, note)
    VALUES (
      product_row.id,
      _quantity_delta,
      _quantity_delta,
      'Ajuste: ' || btrim(_reason)
    );
  END IF;

  UPDATE public.products
  SET stock = next_stock
  WHERE id = product_row.id;

  INSERT INTO public.inventory_adjustments (
    product_id,
    product_name,
    previous_stock,
    quantity_delta,
    new_stock,
    reason,
    user_id,
    user_email
  )
  VALUES (
    product_row.id,
    product_row.name,
    product_row.stock,
    _quantity_delta,
    next_stock,
    btrim(_reason),
    auth.uid(),
    auth.jwt() ->> 'email'
  )
  RETURNING id INTO adjustment_id;

  INSERT INTO public.activity_log (actor_id, action, details)
  VALUES (
    auth.uid(),
    'inventory_adjusted',
    jsonb_build_object(
      'product_id', product_row.id,
      'product_name', product_row.name,
      'quantity', _quantity_delta,
      'reason', btrim(_reason)
    )
  );

  RETURN adjustment_id;
END
$$;

CREATE OR REPLACE FUNCTION public.enqueue_whatsapp_inventory_activity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  activity jsonb;
  notification_kind text;
  activity_label text;
  quantity_text text;
  activity_detail text;
  owner_phone text;
BEGIN
  activity := to_jsonb(NEW);

  IF TG_TABLE_NAME = 'inventory_adjustments' THEN
    notification_kind := 'inventory_adjustment';
    activity_label := 'Ajuste manual de inventario';
    quantity_text := activity ->> 'quantity_delta';
    activity_detail := COALESCE(NULLIF(activity ->> 'reason', ''), 'Sin motivo indicado');
  ELSE
    IF activity ->> 'type' = 'merma' THEN
      notification_kind := 'waste';
      activity_label := 'Merma registrada';
    ELSIF activity ->> 'type' = 'devolucion' THEN
      notification_kind := 'return';
      activity_label := 'Devolución de cliente';
    ELSIF activity ->> 'type' = 'devolucion_proveedor' THEN
      notification_kind := 'supplier_return';
      activity_label := 'Devolución a proveedor';
    ELSIF activity ->> 'type' = 'salida_manual' THEN
      notification_kind := 'manual_out';
      activity_label := 'Salida manual de inventario';
    ELSE
      RETURN NEW;
    END IF;
    quantity_text := concat(activity ->> 'qty', ' ', activity ->> 'unit');
    activity_detail := COALESCE(NULLIF(activity ->> 'note', ''), 'Sin detalle adicional');
  END IF;

  SELECT owner_whatsapp
    INTO owner_phone
  FROM public.settings
  WHERE id = 1
    AND whatsapp_notifications_enabled
    AND inventory_alerts_enabled;

  IF owner_phone IS NULL OR btrim(owner_phone) = '' THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.whatsapp_notifications (
    notification_type,
    recipient,
    message,
    dedupe_key,
    metadata
  )
  VALUES (
    notification_kind,
    owner_phone,
    format(
      '%s: %s. Cantidad: %s. Detalle: %s.',
      activity_label,
      COALESCE(activity ->> 'product_name', 'Producto'),
      quantity_text,
      activity_detail
    ),
    format('inventory-activity:%s:%s', notification_kind, activity ->> 'id'),
    jsonb_build_object(
      'record_id', activity ->> 'id',
      'product_name', activity ->> 'product_name',
      'quantity', quantity_text,
      'detail', activity_detail
    )
  )
  ON CONFLICT (dedupe_key) DO NOTHING;

  RETURN NEW;
END
$$;

